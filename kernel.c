static void text(int x, int y, const char *s, uint32_t c) {
    for (; *s; s++, x += 6) {
        if (*s < 32 || *s > 95) continue;
        const uint8_t *g = FONT[*s - 32];
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (g[row] & (1 << (4 - col)))
                    put(x + col, y + row, c);
    }
}

/* ---- PC speaker beep ---- */
static inline void outb(uint16_t p, uint8_t v) { __asm__ volatile("outb %0,%1"::"a"(v),"Nd"(p)); }

static void beep(uint32_t hz) {
    uint32_t d = 1193180 / hz;
    outb(0x43, 0xB6); outb(0x42, d & 0xFF); outb(0x42, d >> 8);
    outb(0x61, 0x03);
}

static void nobeep(void) { outb(0x61, outb ? 0x00 : 0x00); }

/* ---- Entry point ---- */
void _start(void) {
    if (!fb_req.response || !fb_req.response->framebuffer_count) {
        for (;;) __asm__("hlt");
    }
    struct limine_framebuffer *fb = fb_req.response->framebuffers[0];
    FB = (uint32_t *)fb->address;
    W = fb->width; H = fb->height; PITCH = fb->pitch;

    /* Boot chime: C-E-G */
    beep(523); for (volatile int i = 0; i < 80000000; i++);
    beep(659); for (volatile int i = 0; i < 80000000; i++);
    beep(784); for (volatile int i = 0; i < 80000000; i++);
    nobeep();

    /* Desktop gradient */
    for (int y = 0; y < (int)H; y++) {
        uint8_t r = 0x3A - (0x3A - 0x1E) * y / H;
        uint8_t g = 0x6E - (0x6E - 0x3C) * y / H;
        uint8_t b = 0xA5 - (0xA5 - 0x5A) * y / H;
        rect(0, y, W, 1, 0xFF000000 | (r << 16) | (g << 8) | b);
    }

    /* Dock */
    int dh = 60, dw = 400, dx = (W - dw) / 2, dy = H - dh - 10;
    rect(dx, dy, dw, dh, 0xCC2D2D2D);
    for (int i = 0; i < 5; i++)
        rect(dx + 30 + i * 70, dy + 10, 40, 40, 0xFF4A90D9);

    /* Window */
    int wx = 200, wy = 150, ww = 600, wh = 400;
    rect(wx, wy, ww, wh, 0xFFECECEC);
    rect(wx, wy, ww, 30, 0xFFD4D4D4);
    rect(wx + 10, wy + 8, 12, 12, 0xFFFF5F57);
    rect(wx + 28, wy + 8, 12, 12, 0xFFFFBD2E);
    rect(wx + 46, wy + 8, 12, 12, 0xFF28C840);

    /* Text (Alegreya-style rendering placeholder) */
    text(wx + 70, wy + 12, "MARAOS - WELCOME", 0xFF000000);
    text(wx + 20, wy + 60, "HELLO FROM MARAOS", 0xFF000000);
    text(wx + 20, wy + 80, "BUILT IN C - NO LIBC", 0xFF000000);

    for (;;) __asm__("hlt");
}
