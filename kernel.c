/* ---- Framebuffer globals ---- */
static uint32_t *FB;
static uint64_t W, H, PITCH;

static void put(int x, int y, uint32_t c) {
    if (x < 0 || y < 0 || x >= (int)W || y >= (int)H) return;
    *(uint32_t *)((uint8_t *)FB + y * PITCH + x * 4) = c;
}

static void rect(int x, int y, int w, int h, uint32_t c) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            put(x + i, y + j, c);
}

